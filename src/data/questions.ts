import type { CategoryId, Grade, Question, Source, Verification } from '../types'
import { SRC, TEXTBOOK } from './sources'

interface Spec {
  id: string
  g: Grade
  c: CategoryId
  d: 1 | 2 | 3
  stem: string
  neg?: boolean
  /** [選択肢文, その選択肢が正しい/誤りである理由] */
  ch: [string, string][]
  /** 正答の選択肢記号（例: 'b' / 'ac'） */
  ans: string
  goro: string
  exp: string
  les: string
  v?: Verification
  src?: Source[]
  law?: string
  note?: string
}

const L = 'abcdef'
function mk(s: Spec): Question {
  const ans = s.ans.split('')
  return {
    id: s.id, grade: s.g, category: s.c, difficulty: s.d, stem: s.stem,
    multi: ans.length > 1, negative: s.neg,
    choices: s.ch.map(([text, explanation], i) => ({ id: L[i], text, explanation })),
    answer: ans, mnemonic: s.goro, explanation: s.exp, lessonIds: [s.les],
    origin: 'original', sources: s.src ?? [TEXTBOOK], verification: s.v ?? 'textbook',
    lawBasisDate: s.law, note: s.note,
  }
}

